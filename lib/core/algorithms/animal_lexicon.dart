/// 입력 토큰 정규화: 공백·구두점 제거, 소문자화, 흔한 복수 접미사('들') 제거.
String _normalize(String token) {
  var w = token.toLowerCase().replaceAll(RegExp(r'[^0-9a-z가-힣]'), '');
  if (w.length > 1 && w.endsWith('들')) {
    final stem = w.substring(0, w.length - 1);
    if (_matchAnimal(stem) != null) w = stem;
  }
  return w;
}

/// 단어가 동물이면 대표 이름(사전 표제어)을, 아니면 null을 반환.
String? _matchAnimal(String word) {
  if (word.isEmpty) return null;
  if (_exactOnlyAnimals.contains(word) || _animals.contains(word)) {
    return word;
  }
  // 수식어 + 동물 이름 (예: 검은고양이, 아기돼지). 가장 긴 접미사를 우선.
  for (int start = 1; start < word.length - 1; start++) {
    final suffix = word.substring(start);
    if (_animals.contains(suffix)) return suffix;
  }
  return null;
}

/// 단어 하나가 인정되는 동물 이름인지 확인.
bool isAnimalName(String word) => _matchAnimal(_normalize(word)) != null;

/// T2 입력 텍스트에서 유효한 동물 이름 수(중복 제외)를 센다.
///
/// [input]: 쉼표·공백·줄바꿈으로 구분된 사용자 입력
/// Returns: 서로 다른 동물 이름 수
int countValidAnimalNames(String input) {
  final matched = <String>{};
  for (final token in input.split(RegExp(r'[,，、/;·\s]+'))) {
    final animal = _matchAnimal(_normalize(token));
    if (animal != null) matched.add(animal);
  }
  return matched.length;
}
